using System.Globalization;
using System.Text;

namespace SMSpardaTas;

public sealed record GeneratorOptions(bool Hud = true, string? SavestateBaseDirectory = null);

public sealed record GeneratorResult(string Lua, long FixedFrames, int Waits, int Steps, IReadOnlyList<string> Warnings);

/// <summary>
/// Turns a parsed script into a standalone BizHawk Lua playback script. Repeat blocks are expanded at
/// compile time into a flat step table, and a small runtime loop plays it back one emulator
/// frame at a time: set the joypad, advance a frame, repeat.
/// </summary>
public static class LuaGenerator
{
	public const int MaxSteps = 250_000;

	public static GeneratorResult Generate(TasScript script, GeneratorOptions options)
	{
		List<string> warnings = [];
		List<Statement> steps = [];
		Flatten(script, script.Statements, steps);

		Dictionary<(Expr, string), int> conditions = [];
		List<(Expr Expr, string Text)> conditionList = [];
		SortedSet<int> masks = [0];
		long fixedFrames = 0;
		int waits = 0;
		foreach (Statement step in steps)
		{
			switch (step)
			{
				case InputStatement input:
					masks.Add((int)input.Buttons);
					fixedFrames += input.Frames;
					break;
				case WaitUntilStatement wait:
					masks.Add((int)wait.Hold);
					AddCondition(wait.Condition, wait.ConditionText);
					waits++;
					break;
				case AssertStatement assert:
					AddCondition(assert.Condition, assert.ConditionText);
					break;
			}
		}
		if (script.Savestate == null)
		{
			warnings.Add("no @savestate: playback starts from whatever frame the emulator is on when the script is loaded, so it won't be repeatable");
		}

		StringBuilder lua = new();
		lua.AppendLine($"-- Generated by SMSpardaTas from {Path.GetFileName(script.SourceName)} for BizHawk.");
		lua.AppendLine("-- Don't edit this file: change the .tas script and compile it again.");
		lua.AppendLine("-- Open it from BizHawk's Tools > Lua Console (Script > Open Script).");
		lua.AppendLine();
		lua.AppendLine($"local SCRIPT = {LuaString(Path.GetFileName(script.SourceName))}");
		lua.AppendLine($"local HUD = {(options.Hud ? "true" : "false")}");
		lua.AppendLine();
		lua.Append(Helpers);
		lua.AppendLine();
		AppendBindings(lua, script, options);
		lua.AppendLine();

		lua.AppendLine("local MASKS = {");
		foreach (int mask in masks)
		{
			lua.AppendLine($"\t[{LuaNumber(mask)}] = {LuaString(ButtonNames.Format((Buttons)mask))},");
		}
		lua.AppendLine("}");
		lua.AppendLine();

		lua.AppendLine("local CONDS = {");
		for (int i = 0; i < conditionList.Count; i++)
		{
			(Expr expr, string text) = conditionList[i];
			lua.AppendLine($"\t[{i + 1}] = {{");
			lua.AppendLine($"\t\ttest = function() return {LuaExpr(expr)} end,");
			lua.AppendLine($"\t\ttext = {LuaString(text)},");
			lua.AppendLine($"\t\tdump = function() return {DumpExpr(expr)} end,");
			lua.AppendLine("\t},");
		}
		lua.AppendLine("}");
		lua.AppendLine();

		lua.AppendLine("-- { \"input\", line, mask, frames }  { \"wait\", line, cond, hold mask, timeout }");
		lua.AppendLine("-- { \"assert\", line, cond, message }  { \"label\", line, text }");
		lua.AppendLine("local STEPS = {");
		foreach (Statement step in steps)
		{
			lua.AppendLine(step switch
			{
				InputStatement s => $"\t{{ \"input\", {s.Line}, {LuaNumber((int)s.Buttons)}, {s.Frames} }}, -- {ButtonNames.Format(s.Buttons)}",
				WaitUntilStatement s => $"\t{{ \"wait\", {s.Line}, {conditions[(s.Condition, s.ConditionText)]}, {LuaNumber((int)s.Hold)}, {s.Timeout} }},",
				AssertStatement s => $"\t{{ \"assert\", {s.Line}, {conditions[(s.Condition, s.ConditionText)]}, {(s.Message == null ? "false" : LuaString(s.Message))} }},",
				LabelStatement s => $"\t{{ \"label\", {s.Line}, {LuaString(s.Text)} }},",
				_ => throw new InvalidOperationException($"unexpected step {step.GetType().Name}")
			});
		}
		lua.AppendLine("}");
		lua.AppendLine();
		lua.Append(Runtime);

		return new GeneratorResult(lua.ToString(), fixedFrames, waits, steps.Count, warnings);

		void AddCondition(Expr expr, string text)
		{
			if (!conditions.ContainsKey((expr, text)))
			{
				conditionList.Add((expr, text));
				conditions[(expr, text)] = conditionList.Count;
			}
		}
	}

	private static void Flatten(TasScript script, IReadOnlyList<Statement> statements, List<Statement> output)
	{
		foreach (Statement statement in statements)
		{
			if (statement is RepeatStatement repeat)
			{
				for (int i = 0; i < repeat.Count; i++)
				{
					Flatten(script, repeat.Body, output);
				}
			}
			else
			{
				output.Add(statement);
			}
			if (output.Count > MaxSteps)
			{
				throw new ScriptException(script.SourceName, statement.Line, 1,
					$"the script expands to more than {MaxSteps} steps; use fewer or smaller repeat blocks");
			}
		}
	}

	private static void AppendBindings(StringBuilder lua, TasScript script, GeneratorOptions options)
	{
		IEnumerable<string> pad = ButtonNames.All.Select(b => $"{{ {LuaNumber((int)b)}, {LuaString(b.ToString())} }}");
		lua.AppendLine("-- Emulator bindings: BizHawk (SNES core, WRAM domain)");
		lua.AppendLine($"local PAD = {{ {string.Join(", ", pad)} }}");
		lua.AppendLine("local function set_input(mask)");
		lua.AppendLine("\tlocal pad = {}");
		lua.AppendLine("\tfor i = 1, #PAD do pad[PAD[i][2]] = has(mask, PAD[i][1]) end");
		lua.AppendLine("\tjoypad.set(pad, 1)");
		lua.AppendLine("end");
		lua.AppendLine("local function rd_u8(a) return memory.read_u8(a - 0x7E0000, \"WRAM\") end");
		lua.AppendLine("local function rd_s8(a) return memory.read_s8(a - 0x7E0000, \"WRAM\") end");
		lua.AppendLine("local function rd_u16(a) return memory.read_u16_le(a - 0x7E0000, \"WRAM\") end");
		lua.AppendLine("local function rd_s16(a) return memory.read_s16_le(a - 0x7E0000, \"WRAM\") end");
		lua.AppendLine("local function frameadvance() emu.frameadvance() end");
		lua.AppendLine("local function pause() client.pause() end");
		lua.AppendLine("local function log(message) console.log(message) end");
		lua.AppendLine("local function draw(x, y, text) gui.text(x, y, text) end");

		SavestateDirective? savestate = script.Savestate;
		string load = savestate switch
		{
			{ Path: string path } => $"savestate.load({LuaString(ResolvePath(path, options.SavestateBaseDirectory))})",
			{ Slot: int slot } => $"savestate.loadslot({slot})",
			_ => ""
		};
		lua.AppendLine($"local function load_start() {load} end");
	}

	private static string ResolvePath(string path, string? baseDirectory)
	{
		if (Path.IsPathRooted(path) || baseDirectory == null)
		{
			return path;
		}
		return Path.GetFullPath(Path.Combine(baseDirectory, path));
	}

	public static string LuaExpr(Expr expr)
	{
		return expr switch
		{
			NumberExpr n => LuaNumber(n.Value),
			MemoryExpr m => $"rd_{m.Type.ToString().ToLowerInvariant()}({LuaNumber(m.Address)})",
			NotExpr n => $"(not {LuaExpr(n.Operand)})",
			BinaryExpr { Op: "&" } b => $"band({LuaExpr(b.Left)}, {LuaExpr(b.Right)})",
			BinaryExpr b => $"({LuaExpr(b.Left)} {(b.Op == "!=" ? "~=" : b.Op)} {LuaExpr(b.Right)})",
			_ => throw new InvalidOperationException($"unexpected expression {expr.GetType().Name}")
		};
	}

	/// <summary>A Lua expression that renders every variable the condition reads, for failure messages.</summary>
	private static string DumpExpr(Expr expr)
	{
		List<MemoryExpr> reads = [];
		Collect(expr);
		if (reads.Count == 0)
		{
			return "\"no variables\"";
		}
		IEnumerable<string> parts = reads.Select(m =>
		{
			string read = LuaExpr(m);
			bool signed = m.Type is RamType.S8 or RamType.S16;
			string format = signed ? $"{m.Display}=%d" : $"{m.Display}=%d (0x%0{RamMap.Size(m.Type) * 2}X)";
			string args = signed ? read : $"{read}, {read}";
			return $"string.format({LuaString(format)}, {args})";
		});
		return string.Join(" .. \"  \" .. ", parts);

		void Collect(Expr e)
		{
			switch (e)
			{
				case MemoryExpr m when !reads.Contains(m):
					reads.Add(m);
					break;
				case BinaryExpr b:
					Collect(b.Left);
					Collect(b.Right);
					break;
				case NotExpr n:
					Collect(n.Operand);
					break;
			}
		}
	}

	public static string LuaNumber(long value)
	{
		if (value < 0)
		{
			return "(-" + LuaNumber(-value) + ")";
		}
		return value < 10
			? value.ToString(CultureInfo.InvariantCulture)
			: "0x" + value.ToString("X", CultureInfo.InvariantCulture);
	}

	public static string LuaString(string value)
	{
		StringBuilder sb = new("\"");
		foreach (char c in value)
		{
			sb.Append(c switch
			{
				'\\' => "\\\\",
				'"' => "\\\"",
				'\n' => "\\n",
				'\r' => "\\r",
				_ => c.ToString()
			});
		}
		return sb.Append('"').ToString();
	}

	// Plain arithmetic instead of Lua 5.4 bit operators, so the tests can also run the output
	// under MoonSharp (Lua 5.2).
	private const string Helpers = """
		local function has(mask, bit) return math.floor(mask / bit) % 2 == 1 end
		local function band(a, b)
			local result, bit = 0, 1
			while a > 0 and b > 0 do
				if a % 2 == 1 and b % 2 == 1 then result = result + bit end
				a, b, bit = math.floor(a / 2), math.floor(b / 2), bit * 2
			end
			return result
		end

		""";

	private const string Runtime = """
		local frame = 0
		local current_label = ""

		local function show(line, mask)
			if not HUD then return end
			draw(2, 2, string.format("SMSpardaTas  line %d  frame %d  %s", line, frame, MASKS[mask] or "?"))
			if current_label ~= "" then draw(2, 14, current_label) end
		end

		local function step(line, mask)
			set_input(mask)
			show(line, mask)
			frameadvance()
			frame = frame + 1
		end

		local function fail(line, message)
			log(string.format("SMSpardaTas: %s line %d: %s (at playback frame %d)", SCRIPT, line, message, frame))
			pause()
		end

		local function run()
			for i = 1, #STEPS do
				local s = STEPS[i]
				local kind, line = s[1], s[2]
				if kind == "input" then
					for _ = 1, s[4] do step(line, s[3]) end
				elseif kind == "wait" then
					local cond, waited = CONDS[s[3]], 0
					while not cond.test() do
						if s[5] > 0 and waited >= s[5] then
							return fail(line, "wait_until " .. cond.text .. " timed out after " .. s[5] .. " frames; " .. cond.dump())
						end
						step(line, s[4])
						waited = waited + 1
					end
				elseif kind == "assert" then
					local cond = CONDS[s[3]]
					if not cond.test() then
						return fail(line, (s[4] or "assert failed") .. ": " .. cond.text .. "; " .. cond.dump())
					end
				elseif kind == "label" then
					current_label = s[3]
					log(string.format("SMSpardaTas: frame %d: %s", frame, s[3]))
				end
			end
			log(string.format("SMSpardaTas: %s finished after %d frames", SCRIPT, frame))
			pause()
		end

		load_start()
		run()

		""";
}
